import assert from "node:assert/strict"
import { describe, it } from "node:test"
import { ROOT_LOCALE } from "../lib/content-files.mjs"
import { checkLink, checkLocaleParity, checkNavigation, checkPage, checkRedirects } from "../lib/content-rules.mjs"

const BASE = "/dline"

/**
 * @param {string} relativePath
 * @param {string} locale
 * @param {string} slug
 */
const page = (relativePath, locale, slug) => ({ relativePath, locale, slug })

const ZH = "zh-cn"
const enHome = page("index.mdx", ROOT_LOCALE, "")
const zhHome = page("zh-cn/index.mdx", ZH, "")
const enGuide = page("guide.mdx", ROOT_LOCALE, "guide")
const zhGuide = page("zh-cn/guide.mdx", ZH, "guide")

describe("checkLink", () => {
	/**
	 * @param {string} url
	 * @param {string} [locale]
	 * @param {"link" | "image" | "attribute"} [kind]
	 * @param {string} [basePrefix]
	 */
	const check = (url, locale = ROOT_LOCALE, kind = "link", basePrefix = BASE) => checkLink({ url, kind }, locale, basePrefix)

	it("accepts external, protocol-relative and in-page links", () => {
		for (const url of ["https://github.com/", "mailto:a@b.c", "//cdn.example.com/x", "#section", ""]) {
			assert.equal(check(url), undefined, url)
		}
	})

	it("rejects relative page links but allows relative images", () => {
		assert.match(check("getting-started/") ?? "", /relative link/)
		assert.equal(check("./diagram.png", ROOT_LOCALE, "image"), undefined)
	})

	it("rejects links that hard-code the deployment base", () => {
		assert.match(check("/dline/guide/") ?? "", /hard-codes the site base/)
		assert.match(check("/dline") ?? "", /hard-codes the site base/)
		assert.equal(check("/dline/guide/", ROOT_LOCALE, "link", ""), undefined, "no base, nothing to hard-code")
	})

	it("rejects source-file links and missing trailing slashes", () => {
		assert.match(check("/guide.mdx") ?? "", /source file/)
		assert.match(check("/guide") ?? "", /trailing slash/)
		assert.equal(check("/guide/?tab=1#install"), undefined)
	})

	it("treats paths with a file extension as assets", () => {
		assert.equal(check("/images/logo.png"), undefined)
	})

	it("keeps each locale linking to its own edition", () => {
		assert.match(check("/zh-cn/guide/") ?? "", /English page links to a Chinese page/)
		assert.match(check("/zh-cn/") ?? "", /English page links to a Chinese page/)
		assert.match(check("/guide/", ZH) ?? "", /Chinese page links to an English page/)
		assert.equal(check("/zh-cn/guide/", ZH), undefined)
		assert.equal(check("/guide/"), undefined)
		assert.equal(check("/zh-cnx/guide/"), undefined, "only the exact locale segment marks the Chinese edition")
	})

	it("lets both editions share root-relative assets", () => {
		assert.equal(check("/assets/ui/demo.gif", ZH, "image"), undefined)
		assert.equal(check("/assets/ui/demo.gif", ROOT_LOCALE, "image"), undefined)
	})
})

describe("checkLocaleParity", () => {
	it("accepts topics published in both locales", () => {
		assert.deepEqual(checkLocaleParity([zhHome, enHome, zhGuide, enGuide]), [])
	})

	it("reports the missing counterpart in either direction", () => {
		const issues = checkLocaleParity([enHome, zhHome, enGuide, page("zh-cn/extra.mdx", ZH, "extra")])
		assert.deepEqual(
			issues.map((issue) => issue.message),
			['missing Chinese counterpart for "guide"', 'missing English counterpart for "extra"'],
		)
	})
})

describe("checkNavigation", () => {
	it("accepts listed and explicitly unlisted pages", () => {
		assert.deepEqual(checkNavigation([zhHome, enHome, zhGuide, enGuide], ["guide"], new Set([""])), [])
	})

	it("accepts pages covered by an autogenerated directory", () => {
		const pages = [page("usage/ide.mdx", ROOT_LOCALE, "usage/ide"), page("zh-cn/usage/ide.mdx", ZH, "usage/ide")]
		assert.deepEqual(checkNavigation(pages, [{ items: [{ autogenerate: { directory: "usage" } }] }], new Set()), [])
	})

	it("requires a publication decision for every root-locale page", () => {
		const issues = checkNavigation([enHome, zhHome, enGuide, zhGuide], [], new Set([""]))
		assert.equal(issues.length, 1)
		assert.equal(issues[0]?.file, "guide.mdx")
	})

	it("requires every sidebar slug to exist in both locales", () => {
		const issues = checkNavigation([enHome, zhHome, enGuide], [{ slug: "guide" }], new Set([""]))
		assert.deepEqual(
			issues.map((issue) => issue.message),
			['sidebar slug "guide" has no zh-cn page'],
		)
	})
})

describe("checkRedirects", () => {
	const pages = [zhHome, enHome, zhGuide, enGuide]

	it("accepts redirects from retired paths to current pages", () => {
		assert.deepEqual(checkRedirects({ "/old-guide": "/guide/", "/zh-cn/old-guide": "/zh-cn/guide/#install" }, pages), [])
	})

	it("reports shadowing, chains, dangling targets and non-root-relative paths", () => {
		const messages = checkRedirects(
			{
				"/guide": "/zh-cn/guide/",
				"/a": "/b/",
				// Must not target "/guide/": that path is itself a redirect source above.
				"/b": "/zh-cn/guide/",
				"/gone": "/missing/",
				relative: "/guide/",
			},
			pages,
		).map((issue) => issue.message)
		assert.deepEqual(messages, [
			"redirect source /guide shadows an existing page",
			"redirect /a -> /b/ forms a chain; point it at the final page",
			"redirect /gone -> /missing/ does not target a current page",
			"redirect relative -> /guide/ must use base-free root-relative paths",
		])
	})
})

describe("checkPage", () => {
	/**
	 * @param {ReturnType<typeof page>} identity
	 * @param {string} source
	 */
	const messages = (identity, source) => checkPage({ page: identity, source, basePrefix: BASE }).map((issue) => issue.message)

	it("accepts a well-formed page", () => {
		const source = "---\ntitle: Guide\ndescription: How to start.\n---\n\nSee [install](/guide/).\n"
		assert.deepEqual(messages(enGuide, source), [])
		const chinese = "---\ntitle: 指南\ndescription: 如何开始。\n---\n\n参见[安装](/zh-cn/guide/)。\n"
		assert.deepEqual(messages(zhGuide, chinese), [])
	})

	it("requires Starlight frontmatter and rejects Mintlify-only fields", () => {
		assert.deepEqual(messages(zhGuide, "---\ntitle: 指南\nsidebarTitle: 指南\n---\n\n正文\n"), [
			'missing frontmatter "description"',
			'Mintlify-only frontmatter "sidebarTitle"; remove it or use a Starlight field',
		])
	})

	it("reports unconverted components with the line they appear on", () => {
		const issues = checkPage({
			page: zhGuide,
			source: "---\ntitle: 指南\ndescription: 说明\n---\n\n<Note>提示</Note>\n",
			basePrefix: BASE,
		})
		assert.equal(issues.length, 1)
		assert.equal(issues[0]?.line, 6)
		assert.match(issues[0]?.message ?? "", /<Note> is not imported/)
	})

	it("accepts imported components and ignores tags inside code", () => {
		const source = [
			"---",
			"title: 指南",
			"description: 说明",
			"---",
			"import { Aside } from '@astrojs/starlight/components'",
			"",
			"<Aside>提示</Aside>",
			"",
			"```mdx",
			"<Note>code sample</Note>",
			"```",
		].join("\n")
		assert.deepEqual(messages(zhGuide, source), [])
	})

	it("flags Chinese prose in an English page but not Chinese inside code", () => {
		const withCode = "---\ntitle: Guide\ndescription: Start.\n---\n\n```text\n你好\n```\n"
		assert.deepEqual(messages(enGuide, withCode), [])
		assert.deepEqual(messages(enGuide, "---\ntitle: Guide\ndescription: Start.\n---\n\n你好\n"), [
			"Chinese text in an English page",
		])
	})

	it("flags forbidden tracking and retired runtime references", () => {
		const source = '---\ntitle: 指南\ndescription: 说明\n---\n\n<script src="https://js.hs-scripts.com/1.js"></script>\n'
		assert.ok(messages(zhGuide, source).includes("HubSpot tracking"))
	})
})
