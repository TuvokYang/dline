// Generated artifact provenance private to this Skill. It observes projections and never runs generators.

import fs from "node:fs"
import path from "node:path"

function normalized(filePath) {
    return filePath.replaceAll("\\", "/")
}

function sourceFromHeader(content) {
    const match = /^\s*\/\/\s*source:\s*(\S+)\s*$/m.exec(content)
    return match?.[1] ?? null
}

function generatorFromHeader(content) {
    const match = /^\s*\/\/\s*Generated by\s+(.+)\s*$/im.exec(content)
    return match?.[1]?.trim() ?? null
}

function filesUnder(directory) {
    const files = []
    const walk = (current) => {
        for (const entry of fs.readdirSync(current, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
            const absolute = path.join(current, entry.name)
            if (entry.isDirectory()) walk(absolute)
            else if (entry.isFile()) files.push(absolute)
        }
    }
    walk(directory)
    return files
}

export function defaultGeneratedArtifacts() {
    return []
}

export function readGeneratedProvenance({ repoRoot = process.cwd(), artifacts = defaultGeneratedArtifacts() } = {}) {
    const absoluteRoot = path.resolve(repoRoot)
    const records = []
    for (const artifact of artifacts) {
        const declaredAbsolute = path.resolve(absoluteRoot, artifact.path)
        if (!fs.existsSync(declaredAbsolute)) {
            records.push({
                path: normalized(artifact.path),
                absolute: declaredAbsolute,
                kind: artifact.kind,
                generator: normalized(artifact.generator),
                sourceRoot: normalized(artifact.sourceRoot ?? "proto"),
                state: "missing",
                canonicalSource: null,
                sourceExists: null,
                freshness: "unverified",
            })
            continue
        }
        const stat = fs.statSync(declaredAbsolute)
        const targets = stat.isDirectory() ? filesUnder(declaredAbsolute) : [declaredAbsolute]
        for (const absolute of targets) {
            const textArtifact = /\.(?:[cm]?[jt]s|tsx|jsx)$/.test(absolute)
            const content = textArtifact ? fs.readFileSync(absolute, "utf8") : ""
            const sourceHint = sourceFromHeader(content)
            const canonicalSource = sourceHint ? normalized(path.join(artifact.sourceRoot ?? "", sourceHint)) : null
            records.push({
                path: normalized(path.relative(absoluteRoot, absolute)),
                absolute,
                kind: artifact.kind,
                generator: normalized(generatorFromHeader(content) ?? artifact.generator),
                sourceRoot: normalized(artifact.sourceRoot ?? "proto"),
                state: "present",
                canonicalSource,
                sourceExists: canonicalSource ? fs.existsSync(path.resolve(absoluteRoot, canonicalSource)) : null,
                freshness: "unverified",
            })
        }
    }
    return records
}
