import assert from "node:assert/strict"
import fs from "node:fs"
import os from "node:os"
import path from "node:path"
import test from "node:test"

import { createCodeFactSnapshot } from "../lib/code-facts.mjs"
import { defaultGeneratedArtifacts, readGeneratedProvenance } from "../lib/generated-provenance.mjs"
import { readProtoFacts, readProtoServiceFacts } from "../lib/proto-facts.mjs"

function fixture(t) {
    const root = fs.mkdtempSync(path.join(os.tmpdir(), "dline-code-facts-"))
    t.after(() => fs.rmSync(root, { recursive: true, force: true }))
    return root
}

function write(root, relative, content) {
    const target = path.join(root, relative)
    fs.mkdirSync(path.dirname(target), { recursive: true })
    fs.writeFileSync(target, content)
    return target
}

test("reads canonical Proto service facts including streaming direction", (t) => {
    const root = fixture(t)
    write(
        root,
        "proto/demo/service.proto",
        `syntax = "proto3";
         package demo /* gap */ . v1;
         service DemoService {
           rpc unary(Request) returns (Response);
           rpc watch(stream Request) returns (stream Response);
         }
         message Request {}
         message Response {}
        `,
    )
    const facts = readProtoServiceFacts({ repoRoot: root, protoRoot: "proto" })
    assert.equal(facts[0].fullName, "demo.v1.DemoService")
    assert.deepEqual(
        facts[0].methods.map(({ name, requestStream, responseStream }) => ({ name, requestStream, responseStream })),
        [
            { name: "unary", requestStream: false, responseStream: false },
            { name: "watch", requestStream: true, responseStream: true },
        ],
    )
})

test("reports malformed Proto RPC declarations instead of silently dropping facts", (t) => {
    const root = fixture(t)
    write(
        root,
        "proto/broken.proto",
        'syntax = "proto3"; package demo; service BrokenService { rpc broken(Request returns (Response); }',
    )
    const facts = readProtoFacts({ repoRoot: root, protoRoot: "proto" })
    assert.equal(facts.services[0].methods.length, 0)
    assert.match(facts.diagnostics[0].message, /unable to parse rpc declaration/)
})

test("generated provenance is explicit and has no Dline-specific defaults", (t) => {
    const root = fixture(t)
    write(
        root,
        "proto/demo.proto",
        'syntax = "proto3"; package demo; service DemoService { rpc ping(Request) returns (Response); } message Request {} message Response {}\n',
    )
    write(root, "generated/demo.mjs", "// Generated by fixture-generator\n// source: demo.proto\nexport const generated = true\n")
    const artifacts = [
        { path: "generated", kind: "projection", generator: "fixture-generator", sourceRoot: "proto" },
        { path: "generated/missing.mjs", kind: "projection", generator: "fixture-generator", sourceRoot: "proto" },
    ]
    assert.deepEqual(defaultGeneratedArtifacts(), [])
    const provenance = readGeneratedProvenance({ repoRoot: root, artifacts })
    assert.equal(provenance[0].state, "present")
    assert.equal(provenance[0].canonicalSource, "proto/demo.proto")
    assert.equal(provenance[0].generator, "fixture-generator")
    assert.equal(provenance[1].state, "missing")
})

test("composes Proto and explicit generated facts without package or tsconfig", (t) => {
    const root = fixture(t)
    write(
        root,
        "proto/demo.proto",
        'syntax = "proto3"; package demo; service DemoService { rpc ping(Request) returns (Response); } message Request {} message Response {}\n',
    )
    write(root, "generated/demo.mjs", "// source: demo.proto\nexport const generated = true\n")
    const snapshot = createCodeFactSnapshot({
        repoRoot: root,
        protoRoot: "proto",
        generatedArtifacts: [
            { path: "generated/demo.mjs", kind: "projection", generator: "fixture-generator", sourceRoot: "proto" },
        ],
    })
    assert.equal(fs.existsSync(path.join(root, "package.json")), false)
    assert.equal(fs.existsSync(path.join(root, "tsconfig.json")), false)
    assert.deepEqual(snapshot.imports, [])
    assert.equal(snapshot.protoServices[0].fullName, "demo.DemoService")
    assert.deepEqual(
        snapshot.generated.map(({ path: artifactPath, state }) => ({ path: artifactPath, state })),
        [{ path: "generated/demo.mjs", state: "present" }],
    )
    assert.deepEqual(snapshot.diagnostics, [])
})
